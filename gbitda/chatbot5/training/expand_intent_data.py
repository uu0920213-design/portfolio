# 추가 데이터를 데이터프레임으로 변환
rows = []

for intent, questions in extra_data.items():
    for question in questions:
        rows.append({
            "text": question,
            "intent": intent
        })

extra_df = pd.DataFrame(rows)

# 추가 질문 파일 저장
